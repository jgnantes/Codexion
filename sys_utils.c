#include "codexion.h"

long	get_time_ms(void)
{
	struct timeval	time;

	gettimeofday(&time, NULL);
	return ((time.tv_sec * 1000) + (time.tv_usec / 1000));
}
void	msleep(long milliseconds)
{
	usleep(milliseconds * 1000);
}
